export async function seedDefaultForms(): Promise<void> {
  logger.info('Starting default forms seeding check...');

  for (const form of DEFAULT_SAMPLE_FORMS) {
    const existing = await query<RowDataPacket[]>('SELECT id FROM saved_forms WHERE id = ? OR slug = ?', [
      form.id,
      form.slug,
    ]);

    if (existing.length === 0) {
      await query(
        `INSERT INTO saved_forms (
           id, name, slug, description, category, form_type, status,
           source_type, source_name, canvas_layout, controls,
           master_detail_config, actions_config, version
         ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1)`,
        [
          form.id,
          form.name,
          form.slug,
          form.description,
          form.category,
          form.form_type,
          form.status,
          form.source_type,
          form.source_name,
          JSON.stringify(form.canvas_layout),
          JSON.stringify(form.controls),
          form.master_detail_config ? JSON.stringify(form.master_detail_config) : null,
          form.actions_config ? JSON.stringify(form.actions_config) : null,
        ]
      );
      logger.info(`Seeded sample form: ${form.name}`);
    }
  }

  logger.info('Default forms seeding check completed.');
}
